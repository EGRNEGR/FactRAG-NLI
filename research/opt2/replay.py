"""Offline replay of the 0508Z pipeline under a verifier variant and a thinking router.

For every case the logged drafts of a configuration are re-verified in pipeline order:
first draft, then (if the new verifier withholds it with claims) the logged repair draft.
When the new verifier rejects a draft the run had accepted, no repair draft was ever
generated; the case is then counted as withheld (pessimistic for the variant) and reported
in `missing_repair`. The router decides from the replayed non-thinking result whether the
case takes the replayed thinking result, exactly like pipeline.think_retry.

Usage (reproduction check):  python -m research.opt2.replay
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

from generator_verifier import NLIFactVerifier, RawGenerationResult, VerifiedGenerationResult
from pipeline import refusal_reason
from settings import RAGSettings

from research.opt2 import data
from research.opt2.metrics import Outcome, outcome

Router = Callable[[data.CaseRecord, "Replayed"], bool]


def settings(**overrides: Any) -> RAGSettings:
    """The run's verifier settings (.env of the RTX profile) with `overrides`."""
    return RAGSettings(
        _env_file=str(data.ROOT / ".env"),
        mode="development",
        allow_fallback=True,
        **overrides,
    )


def verifier(backend: Any, **overrides: Any) -> NLIFactVerifier:
    return NLIFactVerifier(settings(**overrides), backend=backend)


@dataclass
class Replayed:
    """Replayed result of one configuration on one case."""

    verified: VerifiedGenerationResult | None  # None: refused by the relevance gate
    attempts: int
    missing_repair: bool
    reason: str | None
    drafts: list[VerifiedGenerationResult] = field(default_factory=list)

    @property
    def refused(self) -> bool:
        return self.verified is None or self.verified.refused

    @property
    def published(self) -> str | None:
        return None if self.refused or self.verified is None else self.verified.cleaned_text


def verify(v: NLIFactVerifier, draft: data.Draft) -> VerifiedGenerationResult:
    raw = RawGenerationResult.model_validate(
        {"text": draft.raw_text, "contexts": draft.contexts, "metadata": draft.metadata}
    )
    return v.verify(raw)


_STORE: dict[str, dict[str, Any]] | None = None


def generated_repair(
    record: data.CaseRecord, config: str, attempt: int, current: VerifiedGenerationResult
) -> data.Draft | None:
    """A repair draft generated by research.opt2.repairs for exactly this revision, if any."""
    global _STORE
    from research.opt2 import repairs

    if _STORE is None:
        _STORE = repairs.load_store()
    row = _STORE.get(repairs.key(record.case.id, config, attempt, repairs.revision_of(current)))
    if row is None:
        return None
    first = record.drafts[config][0]
    return data.Draft(
        config=config,
        attempt=attempt,
        thinking=config == "think",
        raw_text=row["raw_text"],
        refused=False,
        claims=[],
        contexts=first.contexts,
        metadata={**first.metadata, "finish_reason": row["finish_reason"]},
    )


def replay_config(
    record: data.CaseRecord, config: str, v: NLIFactVerifier, repairs: int = 1
) -> Replayed:
    drafts = record.drafts[config]
    if not drafts:
        return Replayed(None, 0, False, record.rows[config]["refusal_reason"])
    results = [verify(v, drafts[0])]
    missing = False
    for attempt in range(1, repairs + 1):
        current = results[-1]
        if not current.refused or not current.claims:
            break
        if attempt < len(drafts):
            results.append(verify(v, drafts[attempt]))
            continue
        generated = generated_repair(record, config, attempt, current)
        if generated is None:
            missing = True
            break
        results.append(verify(v, generated))
    final = results[-1]
    return Replayed(final, len(results), missing, refusal_reason(final), results)


def never(record: data.CaseRecord, base: Replayed) -> bool:
    return False


def on_first_llm_refusal(record: data.CaseRecord, base: Replayed) -> bool:
    return base.reason == "llm_refusal" and base.attempts == 1


def on_withheld(record: data.CaseRecord, base: Replayed) -> bool:
    return base.refused and base.reason not in (
        None,
        "relevance_threshold_not_met",
        "context_budget_exceeded",
    )


@dataclass
class CaseResult:
    outcome: Outcome
    thinking: bool
    missing_repair: bool
    base: Replayed
    final: Replayed


def run(
    records: dict[str, data.CaseRecord],
    v: NLIFactVerifier,
    router: Router = on_withheld,
    *,
    base_config: str = "base",
    think_config: str = "think",
    ids: list[str] | None = None,
) -> list[CaseResult]:
    results = []
    for case_id in ids or list(records):
        record = records[case_id]
        base = replay_config(record, base_config, v)
        thinking = router(record, base)
        final = replay_config(record, think_config, v) if thinking else base
        config = think_config if thinking else base_config
        drafts = record.drafts[config]
        o = outcome(
            record,
            vanilla_text=drafts[0].raw_text if drafts else None,
            published_text=final.published,
        )
        results.append(
            CaseResult(o, thinking, base.missing_repair or final.missing_repair, base, final)
        )
    return results


def main() -> None:
    from research.opt2.metrics import pct, summarize
    from research.opt2.nli_models import CachedNLI

    records = data.records(("base", "think"))
    backend = CachedNLI("mdeberta")
    v = verifier(backend)
    agree = total = 0
    for config in ("base", "think"):
        for record in records.values():
            for draft in record.drafts[config]:
                replayed = verify(v, draft)
                total += 1
                agree += replayed.refused == draft.refused and [
                    c.status.value for c in replayed.claims
                ] == [c["status"] for c in draft.claims]
    print(f"draft-level agreement with the logged verification: {agree}/{total}")
    for name, router in (
        ("first-draft LLM refusal", on_first_llm_refusal),
        ("withheld", on_withheld),
    ):
        res = run(records, v, router)
        s = summarize([r.outcome for r in res])
        print(
            name,
            pct(s["factrag_correct"]),
            pct(s["hallucination"]),
            "thinking",
            sum(r.thinking for r in res),
            "missing repair",
            sum(r.missing_repair for r in res),
        )
    print("NLI cache misses (pairs computed now):", backend.misses)


if __name__ == "__main__":
    main()
